import type { LanguageCode } from '../types/commerce';

export interface LanguageOption {
  code: LanguageCode;
  shortLabel: string;
  nativeName: string;
  englishName: string;
  dir: 'ltr' | 'rtl';
}

export const LANGUAGE_OPTIONS: ReadonlyArray<LanguageOption> = [
  { code: 'en', shortLabel: 'EN', nativeName: 'English', englishName: 'English', dir: 'ltr' },
  { code: 'bn', shortLabel: 'বাংলা', nativeName: 'বাংলা', englishName: 'Bengali', dir: 'ltr' },
  { code: 'hi', shortLabel: 'हिन्दी', nativeName: 'हिन्दी', englishName: 'Hindi', dir: 'ltr' },
  { code: 'ar', shortLabel: 'العربية', nativeName: 'العربية', englishName: 'Arabic', dir: 'rtl' },
  { code: 'es', shortLabel: 'ES', nativeName: 'Español', englishName: 'Spanish', dir: 'ltr' },
  { code: 'fr', shortLabel: 'FR', nativeName: 'Français', englishName: 'French', dir: 'ltr' },
];

export function isSupportedLanguage(value: unknown): value is LanguageCode {
  return (
    value === 'en' ||
    value === 'bn' ||
    value === 'hi' ||
    value === 'ar' ||
    value === 'es' ||
    value === 'fr'
  );
}

export function getLanguageOption(lang: LanguageCode): LanguageOption {
  return LANGUAGE_OPTIONS.find((opt) => opt.code === lang) ?? LANGUAGE_OPTIONS[0];
}

